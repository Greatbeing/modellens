#!/usr/bin/env bash
# deploy_status.sh — render STATUS.md to gh-pages (HTML) and push.
# Run from repo root. Requires: gh auth (PAT with repo scope) + pandoc.
set -euo pipefail

REPO="Greatbeing/modellens"
ROOT="${MODELLENS_ROOT:-$(git rev-parse --show-toplevel 2>/dev/null || echo /data/workspace/modellens)}"
STATUS_MD="$ROOT/STATUS.md"
WORKDIR="$ROOT/.deploy-tmp"
HTML_OUT="$WORKDIR/index.html"
REDIRECT_OUT="$WORKDIR/.nojekyll"

# --- 1. sanity ---
[[ -f "$STATUS_MD" ]] || { echo "STATUS.md not found at $STATUS_MD"; exit 1; }
PANDOC="$ROOT/tools/pandoc-3.13/pandoc.exe"
[[ -x "$PANDOC" ]] || { echo "pandoc not found at $PANDOC"; exit 1; }
command -v gh >/dev/null || { echo "gh not installed"; exit 1; }

# --- 2. render markdown -> html (with minimal css) ---
mkdir -p "$WORKDIR"
cat > "$WORKDIR/template.html" <<'EOF'
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>ModelLens Live Status</title>
<style>
  body {font-family: system-ui, sans-serif; max-width: 900px; margin: 2rem auto; padding: 0 1rem; line-height: 1.6;}
  table {border-collapse: collapse; width: 100%; margin: 1rem 0;}
  th, td {border: 1px solid #ddd; padding: 0.5rem; text-align: left;}
  th {background: #f6f8fa;}
  code {background: #f6f8fa; padding: 0.1rem 0.3rem; border-radius: 3px;}
  pre {background: #f6f8fa; padding: 1rem; overflow: auto;}
  h1, h2, h3 {color: #24292e;}
  .badge {display: inline-block; padding: 0.2rem 0.5rem; border-radius: 3px; font-size: 0.85rem; margin-right: 0.5rem;}
  .healthy {background: #dafbe1; color: #2c662d;}
  .degraded {background: #fff8c5; color: #9a6700;}
  .unreliable {background: #ffebe9; color: #cb2431;}
  .quota_blocked {background: #f1f0ff; color: #57606a;}
</style>
</head>
<body>
$body$
<footer style="margin-top:3rem; font-size:0.85rem; color:#666; border-top:1px solid #eee; padding-top:1rem;">
Generated by <a href="https://github.com/Greatbeing/modellens">ModelLens</a> —
<a href="https://github.com/Greatbeing/modellens/blob/main/STATUS.md">raw markdown</a> ·
Updated $date$
</footer>
</body>
</html>
EOF

"$PANDOC" "$STATUS_MD" -f gfm -t html --template="$WORKDIR/template.html" \
  -V date="$(date -u +'%Y-%m-%d %H:%M UTC')" \
  -o "$HTML_OUT" || { echo "pandoc render failed"; exit 1; }

# .nojekyll to disable Jekyll processing
touch "$REDIRECT_OUT"

# --- 3. push to gh-pages ---
cd "$WORKDIR"
git init -q
git config user.name "github-actions[bot]"
git config user.email "github-actions[bot]@users.noreply.github.com"
git checkout -q -B gh-pages
git add -A
git commit -q -m "deploy: live status $(date -u +%Y-%m-%dT%H:%M:%SZ)"
git push -f -q "https://x-access-token:$GH_TOKEN@github.com/$REPO.git" gh-pages 2>/dev/null
echo "Deployed to https://greatbeing.github.io/modellens/"
rm -rf "$WORKDIR"