    t.querySelectorAll("tbody tr").forEach(function(r){
      [].forEach.call(r.cells,function(c,i){
        var x=c.textContent.trim();
        if(V.indexOf(x)>=0){c.innerHTML='<span class="pill v-'+x+'">'+x.replace("_"," ")+"</span>";}
